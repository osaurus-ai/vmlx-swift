#!/usr/bin/env python3
"""Embed vMLX's MiniMax-M3 fused-kernel Metal sources into vmlx-swift, byte for byte.

    python3 scripts/minimax_m3_fused/embed_kernel_sources.py <vmlx checkout> <vmlx commit>

Reads vmlx_engine/models/minimax_m3/kernels/{attn_*,m3_*}.metal and writes
Libraries/MLXLLM/Models/MiniMaxM3FusedKernelSources.swift: one raw string per file (exact text, trailing newline
kept) plus each file's SHA-256, so a test can prove the Swift copy is the Python source. The kernels' host code in
Swift prepends the same `using` / `constexpr` lines Python's `kernels.prefix()` does.
"""
import hashlib
import pathlib
import sys

root = pathlib.Path(sys.argv[1]) / "vmlx_engine/models/minimax_m3/kernels"
commit = sys.argv[2]
names = ["attn_common", "attn_qkv", "attn_heads", "attn_scores", "attn_msa", "attn_oproj",
         "m3_moe_common", "m3_router", "m3_moe_gate_up", "m3_moe_down"]
out = pathlib.Path(__file__).resolve().parents[2] / "Libraries/MLXLLM/Models/MiniMaxM3FusedKernelSources.swift"


def ident(n: str) -> str:
    head, *rest = n.split("_")
    return head + "".join(p[:1].upper() + p[1:] for p in rest)


lines = [
    "// Copyright 2026 Osaurus AI. All rights reserved.",
    "// SPDX-License-Identifier: MIT",
    "//",
    "// GENERATED by scripts/minimax_m3_fused/embed_kernel_sources.py from vMLX (jjang-ai/vmlx)",
    f"// vmlx_engine/models/minimax_m3/kernels/*.metal at {commit}. Do not edit: regenerate. The Metal sources are",
    "// Apache-2.0 (vMLX), created by Jinho Jang (eric@jangq.ai); each string is the file byte for byte.",
    "",
    "enum MiniMaxM3FusedKernelSources {",
    f"    static let vmlxCommit = \"{commit}\"",
    "",
]
digests = []
for n in names:
    text = (root / f"{n}.metal").read_text()
    assert '"""##' not in text
    digests.append((n, hashlib.sha256(text.encode()).hexdigest()))
    lines.append(f"    /// `{n}.metal`")
    lines.append(f"    static let {ident(n)} = ##\"\"\"")
    lines.append(text + "\n" + "\"\"\"##" if text.endswith("\n") else text + "\n\"\"\"##")
    lines.append("")
lines.append("    /// SHA-256 of each file as vMLX ships it (tests compare the strings above against these).")
lines.append("    static let sha256: [String: String] = [")
for n, d in digests:
    lines.append(f"        \"{n}\": \"{d}\",")
lines.append("    ]")
lines.append("")
lines.append("    static let byName: [String: String] = [")
for n in names:
    lines.append(f"        \"{n}\": {ident(n)},")
lines.append("    ]")
lines.append("}")
out.write_text("\n".join(lines) + "\n")
print(out, len(names), "sources")
