#!/usr/bin/env python3
"""Fixtures for the Swift MiniMax-M3.1 DSpark drafter port (`Libraries/MLXLLM/Models/MiniMaxM3DSpark.swift`).

The vMLX Python runtime's MiniMax drafter (`vmlx_engine/dspark/drafter.py`, perf/minimax-m3-msa-select 630929ed:
`minimax_config`, `_load_minimax_drafter`, `minimax_tensor_name`, `write_quantized_minimax_drafter`) is run on tiny
synthetic drafters (no real weights; geometry of tests/test_dspark_minimax_quantized.py: hidden 64, 2 sliding-window
layers of 4 heads / 2 KV heads of 16 with 8 rotary dims, SwiGLU-OAI FFN 128, vocabulary 128, Markov rank 64, window 6,
block 4, taps [1, 3]). Written next to the JSON (the Swift test loads these directories with its own loader):

  dspark/bf16       release names (language_model.model.dspark.layers.N.decoder_layer.*, final_norm), every tensor BF16
  dspark/release    release names, decoder linears MXFP8 (e4m3 bytes + e8m0 weight_scale_inv), fc / norms / heads BF16
  dspark/q-default  write_quantized_minimax_drafter(release): layers affine 4, fc affine 8, heads as stored
  dspark/q-markov8  plan markov8: layers affine 4, fc affine 8, Markov head affine 8
  dspark/q-mixed    plan mixed: layer-1 attention MXFP8 (stored bytes), layer-0 down affine 6, layers affine 4,
                    fc affine 8, markov_w2 affine 8
  dspark/q-heads8   Markov AND confidence heads affine 8 (the quantized-head read path)

The JSON records, per drafter: the parsed flat config (`minimax_config`), every loaded parameter's SHA-256 (MLX names,
row-major bytes) with its module's quantization, and outputs on PRNG inputs (U[-2, 2) on the CPU, regenerated by the
Swift test and digest-checked first):
  single  context of 9 rows (> window 6), one random block of 4 rows, anchor 5: block hidden, head logits, and the
          Markov draft (tokens + confidences) on the candidate path (K = 16, 32) and the full-vocabulary path (K = 0);
  rounds  a context starting at position 17 (restored-prefix base) grown in chunks of 9 / 1 / 3 / 2 / 5 rows; each
          round embeds [anchor, mask x (span - 1)] with a toy embedding table, span = max(block, count), runs the
          block and drafts `count` tokens (4 / 2 / 7 / 4 / 1: 7 > the trained block) on the default K = 32 path.
Digests are SHA-256 of raw row-major bytes (bf16 as uint16).

    <python with mlx 0.32.3 + jang_tools> scripts/minimax_m3_fixtures/generate_dspark_drafter_fixtures.py \\
        --vmlx <vmlx export> --vmlx-commit <sha> --output Tests/MLXLMTests/Fixtures/MiniMaxM3/dspark-parity.json

Fails closed: the window excludes some context rows for some block rows (else the sliding mask proves nothing), the
quantized copies differ from the release (else the comparison is vacuous), every output finite.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import platform
import shutil
import sys
from pathlib import Path

HID, HEADS, KV, HD, ROT, FFN, TAPS, VOCAB, RANK = 64, 4, 2, 16, 8, 128, 2, 128, 64
WINDOW, BLOCK, LAYERS = 6, 4, 2
PRE = "language_model.model.dspark."
MX8 = {"mode": "mxfp8", "group_size": 32, "bits": 8}


def A(b):
    return {"group_size": 64, "bits": b}


PLANS = {
    "q-default": None,
    "q-markov8": {"layers.*": A(4), "fc": A(8), "markov_head.*": A(8), "confidence_head.*": None},
    "q-mixed": {"layers.1.self_attn.*": MX8, "layers.0.mlp.down_proj": A(6), "layers.*": A(4), "fc": A(8),
                "markov_head.markov_w2": A(8), "markov_head.*": None, "confidence_head.*": None},
    "q-heads8": {"layers.*": A(4), "fc": A(8), "markov_head.*": A(8), "confidence_head.*": A(8)},
}
CONTEXT_BASE = 17
ROUNDS = [(9, 5, 4), (1, 17, 2), (3, 99, 7), (2, 3, 4), (5, 64, 1)]   # (new context rows, anchor, count)


def fail(message):
    print(f"FAIL: {message}", file=sys.stderr)
    sys.exit(1)


def raw_config():
    return {"architectures": ["DSparkMiniMaxDraftModel"], "enable_confidence_head": True,
            "confidence_head_with_markov": True, "text_config": {
                "hidden_size": HID, "num_hidden_layers": LAYERS, "num_attention_heads": HEADS,
                "num_key_value_heads": KV, "head_dim": HD, "rotary_dim": ROT, "rms_norm_eps": 1e-6,
                "vocab_size": VOCAB, "dspark_ffn_hidden_size": FFN, "swiglu_alpha": 1.702, "swiglu_limit": 7.0,
                "sliding_window": WINDOW, "dspark_block_size": BLOCK, "rope_theta": 10_000.0,
                "dspark_noise_token_id": VOCAB - 1, "dspark_target_layer_ids": [1, 3], "dspark_markov_rank": RANK,
                "layer_types": ["sliding_attention"] * LAYERS, "dense_intermediate_size": FFN}}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--vmlx", required=True, type=Path)
    ap.add_argument("--vmlx-commit", required=True)
    ap.add_argument("--output", required=True, type=Path)
    a = ap.parse_args()
    sys.path.insert(0, str(a.vmlx))

    import numpy as np
    import mlx.core as mx
    import mlx.nn as nn
    from mlx.utils import tree_flatten

    from vmlx_engine.dspark import drafter as DR

    def digest(x) -> str:
        x = mx.contiguous(x)
        mx.eval(x)
        arr = np.array(x.view(mx.uint16)) if x.dtype == mx.bfloat16 else np.array(x)
        return hashlib.sha256(arr.tobytes()).hexdigest()

    def uniform(n: int, shape, scale: float = 1.0):
        return mx.random.uniform(-2.0, 2.0, shape, key=mx.random.key(n), stream=mx.cpu) * scale

    root = a.output.parent / "dspark"
    if root.exists():
        shutil.rmtree(root)
    root.mkdir(parents=True)

    def write_release(path: Path, mxfp8: bool, seed: int):
        rng = np.random.default_rng(seed)
        bf = lambda *s, k=0.3: mx.array((rng.standard_normal(s) * k).astype(np.float32)).astype(mx.bfloat16)  # noqa
        t = {PRE + "fc.weight": bf(HID, TAPS * HID, k=0.1), PRE + "hidden_norm.weight": bf(HID, k=0.1),
             PRE + "final_norm.weight": bf(HID, k=0.1), PRE + "markov_head.markov_w1.weight": bf(VOCAB, RANK),
             PRE + "markov_head.markov_w2.weight": bf(VOCAB, RANK),
             PRE + "confidence_head.proj.weight": bf(1, HID + RANK), PRE + "confidence_head.proj.bias": bf(1)}
        for L in range(LAYERS):
            p = f"{PRE}layers.{L}.decoder_layer."
            for n in ("input_layernorm", "post_attention_layernorm"):
                t[p + n + ".weight"] = bf(HID, k=0.1)
            for n in ("self_attn.q_norm", "self_attn.k_norm"):
                t[p + n + ".weight"] = bf(HD, k=0.1)
            for n, o, i in (("self_attn.q_proj", HEADS * HD, HID), ("self_attn.k_proj", KV * HD, HID),
                            ("self_attn.v_proj", KV * HD, HID), ("self_attn.o_proj", HID, HEADS * HD),
                            ("mlp.gate_proj", FFN, HID), ("mlp.up_proj", FFN, HID), ("mlp.down_proj", HID, FFN)):
                if mxfp8:
                    sign = rng.integers(0, 2, (o, i)) << 7
                    w = (sign | (rng.integers(5, 9, (o, i)) << 3) | rng.integers(0, 8, (o, i))).astype(np.uint8)
                    t[p + n + ".weight"] = mx.array(w)
                    t[p + n + ".weight_scale_inv"] = mx.array(rng.integers(121, 124, (o, i // 32)).astype(np.uint8))
                else:
                    t[p + n + ".weight"] = bf(o, i, k=1.0 / np.sqrt(i))
        path.mkdir(parents=True)
        mx.save_safetensors(str(path / "model.safetensors"), t, metadata={"format": "pt"})
        (path / "config.json").write_text(json.dumps(raw_config(), indent=1))

    write_release(root / "bf16", mxfp8=False, seed=0)
    write_release(root / "release", mxfp8=True, seed=1)
    for name, plan in PLANS.items():
        DR.write_quantized_minimax_drafter(root / "release", root / name, plan)

    # inputs
    with mx.stream(mx.cpu):
        feats = uniform(1, (1, 9, TAPS * HID)).astype(mx.bfloat16)
        block = uniform(2, (1, BLOCK, HID)).astype(mx.bfloat16)
        head_w = uniform(3, (VOCAB, HID), 0.3).astype(mx.bfloat16)
        table = uniform(4, (VOCAB, HID)).astype(mx.bfloat16)
        chunks = [uniform(10 + i, (1, n, TAPS * HID)).astype(mx.bfloat16) for i, (n, _, _) in enumerate(ROUNDS)]
        mx.eval(feats, block, head_w, table, *chunks)
    head = nn.Linear(HID, VOCAB, bias=False)
    head.weight = head_w
    embed = nn.Embedding(VOCAB, HID)
    embed.weight = table
    inputs = {"feats": digest(feats), "block": digest(block), "head": digest(head_w), "table": digest(table),
              "chunks": [digest(c) for c in chunks]}

    def quant_entry(m):
        if isinstance(m, (nn.QuantizedLinear, nn.QuantizedEmbedding)):
            return {"mode": m.mode, "group_size": int(m.group_size), "bits": int(m.bits)}
        return None

    report = {}
    h_release = None
    for name in ["bf16", "release", *PLANS]:
        path = root / name
        d = DR.load_drafter(path)
        mods = dict(d.named_modules())
        params = {k: {"sha256": digest(v), "dtype": str(v.dtype).split(".")[-1], "shape": list(v.shape)}
                  for k, v in tree_flatten(d.parameters())}
        quant = {p: quant_entry(m) for p, m in mods.items()
                 if isinstance(m, (nn.Linear, nn.Embedding, nn.QuantizedLinear, nn.QuantizedEmbedding))}
        # single call
        d.reset()
        d.add_context(feats)
        h = d(block)
        single = {"h": digest(h), "logits": digest(head(h)), "ctx_len": d.ctx_len}
        for k in (16, 32, 0):
            tok, conf = d.draft(h, mx.array([5]), head, BLOCK, candidates=k)
            mx.eval(tok, conf)
            if not bool(mx.isfinite(conf).all()):
                fail(f"{name}: confidences not finite")
            single[f"tokens{k}"] = [int(t) for t in tok.tolist()]
            single[f"conf{k}"] = digest(conf)
        if name == "release":
            h_release = h
        if name.startswith("q-") and mx.array_equal(h, h_release).item():
            fail(f"{name}: identical to the release drafter (the comparison would be vacuous)")
        # rounds
        d.reset(base=CONTEXT_BASE)
        mask_embed = embed(mx.array([[VOCAB - 1]]))
        rounds = []
        for i, ((n, anchor, count), chunk) in enumerate(zip(ROUNDS, chunks)):
            d.add_context(chunk)
            span = max(BLOCK, count)
            start = d.ctx_len
            if start + span - 1 - WINDOW < d.ctx_base and i >= 1:
                fail("window excludes nothing in a round past the first")
            blk = mx.concatenate([embed(mx.array([[anchor]])),
                                  mx.broadcast_to(mask_embed, (1, span - 1, HID))], axis=1)
            hh = d(blk)
            tok, conf = d.draft(hh, mx.array([anchor]), head, count, candidates=32)
            mx.eval(hh, tok, conf)
            rounds.append({"new_rows": n, "anchor": anchor, "count": count, "span": span, "start": start,
                           "h": digest(hh), "tokens": [int(t) for t in tok.tolist()], "conf": digest(conf)})
        report[name] = {"config": DR.minimax_config(raw_config()), "parameters": params, "quantization": quant,
                        "single": single, "rounds": rounds}
        print(f"{name}: {len(params)} parameters, single tokens32 {single['tokens32']}, rounds "
              f"{[r['tokens'] for r in rounds]}", flush=True)

    # The sliding window really excludes context rows for some block rows and not others (round 3: context of
    # 9 + 1 + 3 rows from 17, block of 7).
    fixture = {
        "generator": "scripts/minimax_m3_fixtures/generate_dspark_drafter_fixtures.py",
        "generator_sha256": hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
        "vmlx_commit": a.vmlx_commit,
        "drafter_py_sha256": hashlib.sha256((a.vmlx / "vmlx_engine/dspark/drafter.py").read_bytes()).hexdigest(),
        "mlx": mx.__version__, "python": platform.python_version(),
        "geometry": {"hidden": HID, "heads": HEADS, "kv_heads": KV, "head_dim": HD, "rotary": ROT, "ffn": FFN,
                     "taps": TAPS, "vocab": VOCAB, "rank": RANK, "window": WINDOW, "block": BLOCK, "layers": LAYERS},
        "context_base": CONTEXT_BASE, "rounds": ROUNDS, "inputs": inputs, "drafters": report,
    }
    a.output.write_text(json.dumps(fixture, indent=None, separators=(",", ":")))
    total = sum(f.stat().st_size for f in root.rglob("*") if f.is_file())
    print(f"wrote {a.output} ({a.output.stat().st_size} bytes) and {root} ({total} bytes)")


if __name__ == "__main__":
    main()
